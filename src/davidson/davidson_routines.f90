SUBROUTINE amul( n, qV, rV )

  !===========================================================================
  !
  ! for Jacobi-Davidson:  rV = A qV 
  !
  !===========================================================================

  USE sparse_matrix_rout, ONLY : matvec_sparse

  !===========================================================================

  IMPLICIT NONE

  !===========================================================================

  INTEGER,                                   INTENT( IN )    :: n
  COMPLEX ( KIND( 0.0D0 ) ), DIMENSION( n ), INTENT( INOUT ) :: qV, rV

  !===========================================================================

  CALL matvec_sparse( n, qV, rV )

  !===========================================================================

END SUBROUTINE amul


!=============================================================================


SUBROUTINE amul_real( n, qV, rV )

  !===========================================================================
  !
  ! for Jacobi-Davidson:  rV = A qV 
  !
  !===========================================================================
  
  USE sparse_matrix_rout_real, ONLY : matvec_sparse_real
  
  !===========================================================================
  
  IMPLICIT NONE

  !===========================================================================
  
  INTEGER,                                   INTENT( IN )  :: n
  COMPLEX ( KIND( 0.0D0 ) ), DIMENSION( n ), INTENT( IN )  :: qV
  COMPLEX ( KIND( 0.0D0 ) ), DIMENSION( n ), INTENT( OUT ) :: rV
  REAL    ( KIND( 0.0D0 ) ), DIMENSION( n )                :: qV_real, rV_real

  !===========================================================================
   
  qV_real = REAL( qV )

  CALL matvec_sparse_real( n, qV_real, rV_real )

  rV = CMPLX( rV_real ) 

  !===========================================================================

END SUBROUTINE amul_real


!=============================================================================


SUBROUTINE bmul( n, qV, rV )
  
  !===========================================================================
  !
  ! for Jacobi-Davidson:  rV = B qV = qV , since B = I
  !
  !===========================================================================

  IMPLICIT NONE

  !===========================================================================

  INTEGER,                                   INTENT( IN )  :: n
  COMPLEX ( KIND( 0.0D0 ) ), DIMENSION( n ), INTENT( IN )  :: qV
  COMPLEX ( KIND( 0.0D0 ) ), DIMENSION( n ), INTENT( OUT ) :: rV

  !===========================================================================

  rV = qV

  !===========================================================================

END SUBROUTINE bmul


!=============================================================================


SUBROUTINE bmul_real( n, qV, rV )

  !===========================================================================
  !
  ! for Jacobi-Davidson:  rV = B qV = qV , since B = I
  !
  !===========================================================================

  IMPLICIT NONE

  !===========================================================================

  INTEGER,                                   INTENT( IN )  :: n
  COMPLEX ( KIND( 0.0D0 ) ), DIMENSION( n ), INTENT( IN )  :: qV
  REAL    ( KIND( 0.0D0 ) ), DIMENSION( n ), INTENT( OUT ) :: rV

  !===========================================================================

  rV = qV

  !===========================================================================

END SUBROUTINE bmul_real


!=============================================================================


SUBROUTINE precon( n, qV )

  !===========================================================================
  !
  ! for Jacobi-Davidson:  qV = K^-1 qV
  !
  !===========================================================================

  USE mod_precond_ilu_davidson, ONLY : davidson_precond_jacV
 
  !===========================================================================

  IMPLICIT NONE

  !===========================================================================

  INTEGER,                                       INTENT( IN )    :: n
  COMPLEX ( KIND( 0.0D0 ) ), DIMENSION( 1 : n ), INTENT( INOUT ) :: qV

  !===========================================================================

  qV = qV * davidson_precond_jacV

  !===========================================================================

END SUBROUTINE precon

!=============================================================================

SUBROUTINE precon_real( n, qV )

  !===========================================================================
  !
  ! for Jacobi-Davidson:  qV = K^-1 qV
  !
  !===========================================================================

  USE mod_precond_ilu_davidson, ONLY : davidson_precond_jacV_real

  !===========================================================================

  IMPLICIT NONE

  !===========================================================================

  INTEGER,                                       INTENT( IN )    :: n
  REAL    ( KIND( 0.0D0 ) ), DIMENSION( 1 : n ), INTENT( INOUT ) :: qV

  !===========================================================================

  qV = qV * davidson_precond_jacV_real

  !===========================================================================

END SUBROUTINE precon_real

